export const getVoiceById = (id: string, customVoices: Voice[] = []): Voice => {
  const all = [...PRESET_VOICES, ...customVoices];
  return all.find(v => v.id === id) || PRESET_VOICES[0];
};

export interface ResolvedVoiceModel {
  voiceCode: string;
  pitchOffset: string;
}

export const getNeuralVoiceForLanguage = (
  voice: Voice,
  langCode: string
): ResolvedVoiceModel => {
  // If English, use the signature base neural model
  if (langCode === 'en' || !langCode) {
    return {
      voiceCode: voice.baseNeuralVoice,
      pitchOffset: voice.clonedMetrics?.pitchOffset || '+0Hz',
    };
  }

  // For non-English languages, select the premier native neural voice actor
  // to ensure 100% fluent native pronunciation, accurate phonemes, and natural prosody
  let targetModel = voice.baseNeuralVoice;
  if (voice.neuralVoiceMap && voice.neuralVoiceMap[langCode]) {
    targetModel = voice.neuralVoiceMap[langCode];
  }

  // Preserve pure unshifted neural vocal cords (+0Hz) across all languages
  // Prevents phase vocoder metallic flanging, harmonic distortion, and robotic timbre
  const pitchOffset = voice.clonedMetrics?.pitchOffset || '+0Hz';

  return {
    voiceCode: targetModel,
    pitchOffset,
  };
};
